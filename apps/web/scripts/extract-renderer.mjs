// Extracts the Three.js avatar renderer out of the mobile WebView template
// (apps/mobile/src/features/avatar/components/AvatarVRM.js buildHTML()) into
// apps/web/src/avatar/three/renderer.js.
//
// The renderer code has ONE canonical home — the mobile file. This script
// re-derives the web module from it with mechanical seam replacements
// (bridge callbacks instead of postMessage, container instead of document.body,
// npm three instead of the CDN importmap). Re-run after editing the source:
//   node scripts/extract-renderer.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(__dirname, '../../mobile/src/features/avatar/components/AvatarVRM.js');
const OUT = path.resolve(__dirname, '../src/avatar/three/renderer.js');

const lines = readFileSync(SRC, 'utf8').split('\n');
const start = lines.findIndex((l) => l.includes('<script type="module">'));
let end = -1;
for (let i = lines.length - 1; i >= 0; i--) {
  if (lines[i].includes('<\\/script>')) { end = i; break; }
}
if (start < 0 || end < 0 || end <= start) throw new Error('module script markers not found');
let body = lines.slice(start + 1, end).join('\n');

// Imports move to module top level (from the CDN importmap to npm three).
body = body.replace(/^import .*;$/gm, '');

const replacements = [
  // model/backdrop URLs come in as factory params instead of interpolations
  ["'${safeUrl}'", 'modelUrl'],
  ["'${safeBackdropUrl}'", 'backdropUrl'],
  // DRACO decoders served locally (apps/web/public/draco/)
  ["'https://cdn.jsdelivr.net/npm/three@0.180.0/examples/jsm/libs/draco/'", "'/draco/'"],
  // debug + status + viseme overlay live inside the container
  ['window._dbg', '_dbg'],
  ["const statusEl = document.getElementById('status');", 'const statusEl = _statusEl;'],
  ["document.getElementById('viseme-dbg')", '_visemeDbgEl'],
  // The WebView styled the canvas via a CSS rule (canvas{width:100%;height:100%});
  // here the style rides along with the element.
  ['document.body.appendChild(renderer.domElement);',
    "renderer.domElement.style.cssText = 'display:block;width:100%;height:100%';\ncontainer.appendChild(renderer.domElement);"],
  // size from the container, not the window
  ['window.innerWidth', '_w()'], ['window.innerHeight', '_h()'],
  // RN bridge → callback shim (always truthy, so the guards keep passing)
  ['window.ReactNativeWebView', '_bridge'],
  // WebView message plumbing is not needed — commands are direct method calls
  ["window.addEventListener('message', handleIncomingMessage);", ''],
  ["document.addEventListener('message', handleIncomingMessage);", ''],
  // window resize → container ResizeObserver
  ["window.addEventListener('resize', () => {", '_onResize(() => {'],
  // RAF loop must be cancellable by dispose()
  ['requestAnimationFrame(animate);', 'if (!_disposed) _raf = requestAnimationFrame(animate);'],
];
for (const [from, to] of replacements) body = body.split(from).join(to);

// Command globals become controller methods.
body = body.replace(/^window\.(\w+) = /gm, 'api.$1 = ');

const header = `// GENERATED by apps/web/scripts/extract-renderer.mjs from
// apps/mobile/src/features/avatar/components/AvatarVRM.js — DO NOT EDIT BY HAND.
// Edit the mobile source (the canonical renderer) and re-run the script.
/* eslint-disable */
import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { DRACOLoader } from 'three/addons/loaders/DRACOLoader.js';
import { MeshoptDecoder } from 'three/addons/libs/meshopt_decoder.module.js';

export function createAvatarRenderer({ container, modelUrl, backdropUrl = null, debug = false, onMessage = () => {} } = {}) {
  const api = {};
  let _raf = 0;
  let _disposed = false;
  const _dbg = (msg) => { if (debug) console.debug('[avatar]', msg); };
  const _bridge = { postMessage: (s) => { try { onMessage(JSON.parse(s)); } catch { /* bad payload */ } } };
  const _w = () => container.clientWidth || 300;
  const _h = () => container.clientHeight || 300;
  const _statusEl = document.createElement('div');
  _statusEl.style.cssText = 'position:absolute;top:8px;left:50%;transform:translateX(-50%);color:#9CB4C4;font:12px ui-monospace,monospace;pointer-events:none;z-index:5';
  container.appendChild(_statusEl);
  const _visemeDbgEl = document.createElement('div');
  _visemeDbgEl.style.cssText = 'position:absolute;top:8px;left:8px;color:#8f8;background:rgba(0,0,0,.55);font:11px ui-monospace,monospace;padding:5px 9px;border-radius:5px;pointer-events:none;display:none;white-space:pre;z-index:20';
  container.appendChild(_visemeDbgEl);
  let _resizeObs = null;
  const _onResize = (fn) => {
    _resizeObs = new ResizeObserver(() => fn());
    _resizeObs.observe(container);
  };

`;

const footer = `

  api.dispose = function() {
    _disposed = true;
    cancelAnimationFrame(_raf);
    try { _resizeObs?.disconnect(); } catch {}
    try { api.stopAudioLipSync(); } catch {}
    try { renderer.dispose(); } catch {}
    try { container.removeChild(renderer.domElement); } catch {}
    try { container.removeChild(_statusEl); } catch {}
    try { container.removeChild(_visemeDbgEl); } catch {}
  };
  return api;
}
`;

// Indent body by 2 spaces to sit inside the factory (cosmetic only).
const indented = body.split('\n').map((l) => (l.trim() ? '  ' + l : l)).join('\n');
writeFileSync(OUT, header + indented + footer);

// Sanity checks — fail loudly if the source drifted from the seams we patch.
const out = readFileSync(OUT, 'utf8');
const mustNotContain = ['${safeUrl}', '${safeBackdropUrl}', 'ReactNativeWebView', 'document.body', 'cdn.jsdelivr.net'];
for (const bad of mustNotContain) {
  if (out.includes(bad)) throw new Error(`extraction left unpatched token: ${bad}`);
}
const mustContain = ['api.setAvatarState', 'api.startStreamingPlayback', 'api.appendAudioChunk', 'api.endStreamingPlayback', 'api.playAudioWithVisemeTimeline', 'api.stopAudioLipSync', 'function animate'];
for (const good of mustContain) {
  if (!out.includes(good)) throw new Error(`extraction missing expected api: ${good}`);
}
console.log(`renderer.js written (${out.length} chars) — all seam checks passed`);
