#!/usr/bin/env node
// Build dementia-speech-style variants of the development question set (E9
// §2.5, "do dementia-speech recognition errors change the answer?").
//
// The error profile comes from the ADReSS alignments (wer-report.mjs
// --profile-out); the example under fixtures/ is a PLACEHOLDER and is
// labelled as such in every output. For each question and level, words are
// deleted / substituted / inserted at the profile's rates (function words
// preferred for deletion in the profile's proportion; substitutions drawn
// from the confusion table when the word is in it, otherwise from a
// phonetically-near candidate in the same question set, otherwise a filler),
// and the `disfluent` level adds fillers, immediate repetitions and
// retracings ("the the boy", "he's, I mean she's") at the CHAT-derived rates
// with NO recognition errors. Seeded, so re-runs are byte-identical.
//
// Output: scripts/eval/questions.perturbed.js exporting PERTURBED_QUESTIONS.
// Ids are `<orig>__<level>`; `relevant` / `acceptable` / `set` / `category`
// are carried over so run-retrieval.mjs and run-generation.mjs score them
// with --questions-file. Achieved word-level error rate against the clean
// wording is recorded per variant (`achievedWer`) — that, not the target, is
// what the report quotes.
//
// Usage:
//   node scripts/eval/stt/perturb-questions.mjs --profile data/dementiabank/error-profile_whisper-1.json
//   node scripts/eval/stt/perturb-questions.mjs --profile scripts/eval/stt/fixtures/error-profile.example.json   # placeholder
//   flags: --sets A,A-neighbour,B,N  --seed 42  --out scripts/eval/questions.perturbed.js  --levels control,ad,ad150,disfluent
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createRequire } from 'node:module';

import { ROOT } from '../lib.mjs';

const require = createRequire(import.meta.url);
const { QUESTIONS, questionText } = require('../questions.js');
const { mulberry32 } = require('../lib/stats.js');
const { wer, FUNCTION_WORDS } = require('../lib/wer.js');
const { perturb } = require('./perturb.js');

const args = process.argv.slice(2);
const argVal = (n) => { const i = args.indexOf(n); return i === -1 ? null : args[i + 1]; };

const PROFILE = resolve(ROOT, argVal('--profile') ?? 'scripts/eval/stt/fixtures/error-profile.example.json');
const SETS = (argVal('--sets') ?? 'A,A-neighbour,B,N').split(',');
const SEED = Number(argVal('--seed') ?? 42);
const OUT = resolve(ROOT, argVal('--out') ?? 'scripts/eval/questions.perturbed.js');
const LEVELS = (argVal('--levels') ?? 'control,ad,ad150,disfluent').split(',');

const profile = JSON.parse(readFileSync(PROFILE, 'utf8'));
const placeholder = /placeholder/i.test(profile.source ?? '');
const rnd = mulberry32(SEED);

const source = QUESTIONS.filter(q => SETS.includes(q.set));
const out = [];
for (const q of source) {
  const clean = questionText(q, 'v2');
  for (const level of LEVELS) {
    const text = perturb(clean, profile, level, rnd, { vocabulary: source.map(s => questionText(s, 'v2')) });
    const a = wer(clean, text, { fillers: 'keep' });
    out.push({
      id: `${q.id}__${level}`, sourceId: q.id, level, set: q.set, category: q.category,
      relevant: q.relevant ?? [], acceptable: q.acceptable ?? [], ...(q.pendingContent ? { pendingContent: true } : {}),
      ...(q.mustMatch ? { mustMatch: q.mustMatch } : {}), ...(q.mustNotMatch ? { mustNotMatch: q.mustNotMatch } : {}),
      question: text, cleanQuestion: clean, achievedWer: Number(a.wer.toFixed(4)),
      note: `${level} variant of ${q.id}; profile ${placeholder ? 'PLACEHOLDER (not measured)' : profile.source}`,
    });
  }
}

const header = `// GENERATED by scripts/eval/stt/perturb-questions.mjs — do not edit.
// Profile: ${profile.source}${placeholder ? '\n// *** PLACEHOLDER PROFILE — these variants are for tooling checks only; nothing derived from them is a result. ***' : ''}
// Seed ${SEED}; sets ${SETS.join(',')}; levels ${LEVELS.join(',')}; ${out.length} variants of ${source.length} questions.
// Achieved word error rate vs the clean wording, mean per level: ${LEVELS.map(l => `${l} ${(100 * out.filter(v => v.level === l).reduce((s, v) => s + v.achievedWer, 0) / Math.max(1, out.filter(v => v.level === l).length)).toFixed(1)}%`).join(', ')}.
// Regexes (mustMatch/mustNotMatch) are carried over from questions.js by reference so safety-checks still apply.
`;
const body = 'const PERTURBED_QUESTIONS = ' + JSON.stringify(out, (k, v) => (v instanceof RegExp ? { __re: v.source, flags: v.flags } : v), 2)
  .replace(/\{\s*"__re":\s*"((?:[^"\\]|\\.)*)",\s*"flags":\s*"([a-z]*)"\s*\}/g, (_, s, f) => `/${s.replace(/\\\\/g, '\\').replace(/\\"/g, '"')}/${f}`)
  + ';\n\nmodule.exports = { PERTURBED_QUESTIONS };\n';
writeFileSync(OUT, header + body);
console.log(`Wrote ${OUT}: ${out.length} variants (${source.length} questions × ${LEVELS.length} levels), seed ${SEED}${placeholder ? ' — PLACEHOLDER profile' : ''}`);
for (const l of LEVELS) {
  const xs = out.filter(v => v.level === l).map(v => v.achievedWer);
  console.log(`  ${l.padEnd(10)} achieved WER mean ${(100 * xs.reduce((s, x) => s + x, 0) / xs.length).toFixed(1)}%`);
}
